#!/usr/bin/env python3
"""Generate the combining-mark table shared by la-text (Rust) and @label-anything/text (TS).

Line breaking (spec §5.3) never breaks before a combining mark and never splits a base
character from its marks when truncating. Both implementations must use the *same* table
so that their results are identical, independent of the Unicode version of the platform.

The table lists every code point whose General_Category is Mn, Mc or Me in Unicode
15.1.0 (the version of Python 3.13's `unicodedata`), as sorted, disjoint, inclusive ranges.

Usage: python3 tools/text/gen_unicode_tables.py [--check]
"""
import sys
import unicodedata
from pathlib import Path

UNICODE_VERSION = "15.1.0"
ROOT = Path(__file__).resolve().parents[2]
RUST_OUT = ROOT / "rust/crates/la-text/src/unicode_data.rs"
TS_OUT = ROOT / "ts/packages/text/src/generated/unicode-data.ts"
BANNER = f"Generated by tools/text/gen_unicode_tables.py from Unicode {UNICODE_VERSION}. DO NOT EDIT."


def mark_ranges():
    ranges, start = [], None
    for cp in range(0x110000):
        is_mark = unicodedata.category(chr(cp)) in ("Mn", "Mc", "Me")
        if is_mark and start is None:
            start = cp
        elif not is_mark and start is not None:
            ranges.append((start, cp - 1))
            start = None
    assert start is None
    return ranges


def rust_source(ranges):
    lines = [
        f"// {BANNER}",
        "",
        "/// Combining marks (General_Category Mn, Mc, Me) as sorted, disjoint, inclusive",
        f"/// code point ranges (Unicode {UNICODE_VERSION}).",
        "#[rustfmt::skip]",
        "pub(crate) const COMBINING_MARKS: &[(u32, u32)] = &[",
    ]
    for i in range(0, len(ranges), 4):
        row = ", ".join(f"(0x{a:04X}, 0x{b:04X})" for a, b in ranges[i:i + 4])
        lines.append(f"    {row},")
    lines.append("];")
    return "\n".join(lines) + "\n"


def ts_source(ranges):
    lines = [
        f"// {BANNER}",
        "",
        "/**",
        " * Combining marks (General_Category Mn, Mc, Me) as sorted, disjoint, inclusive code point",
        f" * ranges, flattened to `[start0, end0, start1, end1, ...]` (Unicode {UNICODE_VERSION}).",
        " */",
        "export const COMBINING_MARKS: Uint32Array = new Uint32Array([",
    ]
    for i in range(0, len(ranges), 4):
        row = ", ".join(f"0x{a:04x}, 0x{b:04x}" for a, b in ranges[i:i + 4])
        lines.append(f"  {row},")
    lines.append("]);")
    return "\n".join(lines) + "\n"


def main():
    if unicodedata.unidata_version != UNICODE_VERSION:
        sys.exit(f"needs Python's unicodedata {UNICODE_VERSION} (Python 3.13), "
                 f"found {unicodedata.unidata_version}")
    check = "--check" in sys.argv[1:]
    ranges = mark_ranges()
    stale = False
    for path, content in ((RUST_OUT, rust_source(ranges)), (TS_OUT, ts_source(ranges))):
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == content:
            continue
        stale = True
        rel = path.relative_to(ROOT)
        if check:
            print(f"stale: {rel}", file=sys.stderr)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"wrote {rel}")
    if check and stale:
        sys.exit(1)
    if not stale:
        print("unicode tables: up to date")


if __name__ == "__main__":
    main()
