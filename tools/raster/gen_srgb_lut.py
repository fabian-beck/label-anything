#!/usr/bin/env python3
"""Generate the sRGB -> linear lookup table used by the OKLab conversion (spec §4.6).

For every 8-bit value i (0..255) the exact real number

    v      = i / 255
    lin(v) = v / 12.92                      if v <= 0.04045   (i <= 10)
           = ((v + 0.055) / 1.055) ** 2.4   otherwise

is rounded ONCE to the nearest IEEE-754 binary64 value (ties to even). The power is
evaluated with exact integer arithmetic, ((1000 i + 14025) / 269025) ** (12/5), as the
integer 5th root of a scaled rational, so no floating-point `pow` is involved and the
table is reproducible bit for bit. The values are written as shortest round-trip
decimal literals (Python `repr`), which Rust and JavaScript both parse exactly to the
same binary64 numbers:

    rust/crates/la-raster/src/srgb_lut.rs
    ts/packages/raster/src/srgb-lut.ts

Usage:
    python3 tools/raster/gen_srgb_lut.py           regenerate both files
    python3 tools/raster/gen_srgb_lut.py --check   exit 1 if a file is stale
"""
import sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RUST_OUT = ROOT / "rust/crates/la-raster/src/srgb_lut.rs"
TS_OUT = ROOT / "ts/packages/raster/src/srgb-lut.ts"
BANNER = "Generated by tools/raster/gen_srgb_lut.py. DO NOT EDIT."

# Fixed-point precision (bits) of the exact root; far more than binary64's 53 bits.
K = 256


def iroot(n: int, k: int) -> int:
    """floor(n ** (1/k)) for a non-negative integer n (exact)."""
    if n < 2:
        return n
    lo, hi = 0, 1 << (n.bit_length() // k + 1)
    while lo < hi:  # largest m with m**k <= n
        mid = (lo + hi + 1) // 2
        if mid ** k <= n:
            lo = mid
        else:
            hi = mid - 1
    return lo


def srgb_to_linear(i: int) -> float:
    if i <= 10:
        # (i / 255) / 12.92 = 100 i / 329460, a rational: int/int division is correctly rounded.
        return float(Fraction(100 * i, 329460))
    p, q = 1000 * i + 14025, 269025  # (i/255 + 0.055) / 1.055 = p / q
    # y = (p^12 / q^12)^(1/5);  Y = floor(y * 2^K) = iroot5(floor(p^12 * 2^(5K) / q^12)).
    big = (p ** 12 << (5 * K)) // q ** 12
    y_lo = iroot(big, 5)
    lo = float(Fraction(y_lo, 1 << K))
    hi = float(Fraction(y_lo + 1, 1 << K))
    # y lies in [lo_exact, hi_exact); rounding is monotone, so equal bounds prove y's rounding.
    assert lo == hi, f"rounding of entry {i} not decided at K={K}"
    return lo


def table() -> list:
    lut = [srgb_to_linear(i) for i in range(256)]
    assert lut[0] == 0.0 and lut[255] == 1.0
    assert all(a < b for a, b in zip(lut, lut[1:])), "LUT must be strictly increasing"
    return lut


def rust_source(lut: list) -> str:
    rows = []
    for k in range(0, 256, 4):
        rows.append("    " + " ".join(f"{repr(v)}," for v in lut[k:k + 4]))
    return (
        f"// {BANNER}\n"
        "//! sRGB 8-bit value -> linear light, exactly rounded (spec §4.6).\n"
        "\n"
        "/// `SRGB_TO_LINEAR[i]` is the sRGB EOTF of `i / 255`, rounded once to binary64.\n"
        "#[rustfmt::skip]\n"
        "pub(crate) const SRGB_TO_LINEAR: [f64; 256] = [\n"
        + "\n".join(rows)
        + "\n];\n"
    )


def ts_source(lut: list) -> str:
    rows = []
    for k in range(0, 256, 4):
        rows.append("  " + " ".join(f"{repr(v)}," for v in lut[k:k + 4]))
    return (
        f"// {BANNER}\n"
        "// sRGB 8-bit value -> linear light, exactly rounded (spec §4.6).\n"
        "\n"
        "/** `SRGB_TO_LINEAR[i]` is the sRGB EOTF of `i / 255`, rounded once to binary64. */\n"
        "export const SRGB_TO_LINEAR: Float64Array = new Float64Array([\n"
        + "\n".join(rows)
        + "\n]);\n"
    )


def main() -> int:
    check = "--check" in sys.argv[1:]
    lut = table()
    stale = False
    for path, content in ((RUST_OUT, rust_source(lut)), (TS_OUT, ts_source(lut))):
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == content:
            continue
        stale = True
        rel = path.relative_to(ROOT)
        if check:
            print(f"stale: {rel}", file=sys.stderr)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {rel}")
    if check and stale:
        print("Run: python3 tools/raster/gen_srgb_lut.py", file=sys.stderr)
        return 1
    if not stale:
        print("gen_srgb_lut: up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
