#!/usr/bin/env node
// Generates implementation constants from the language-neutral spec.
//
//   node tools/codegen.mjs          regenerate all outputs
//   node tools/codegen.mjs --check  fail (exit 1) if any output is stale
//
// Inputs:  spec/defaults.md (table between defaults:begin/end), spec/presets/*.json,
//          spec/schema/*.json, fonts/*.metrics.ttf
// Outputs: rust/crates/la-core/src/generated/spec_data.rs
//          ts/packages/core/src/generated/spec-data.ts
//          ts/packages/core/src/generated/problem.ts, result.ts   (types from the schemas)
//          ts/packages/text/src/generated/fonts.ts                 (base64 metrics fonts)
//          rust/crates/la-text/assets/                             (copies of the metrics fonts + OFL.txt)
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const banner = "Generated by tools/codegen.mjs from the spec/ directory. DO NOT EDIT.";

function parseDefaultsTable(md) {
  const begin = md.indexOf("<!-- defaults:begin -->");
  const end = md.indexOf("<!-- defaults:end -->");
  if (begin < 0 || end < 0) throw new Error("defaults.md: markers not found");
  const rows = md.slice(begin, end).split("\n").filter((l) => l.startsWith("| `"));
  const out = {};
  for (const row of rows) {
    // | `key` | `json` | rule | description |
    const m = row.match(/^\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|/);
    if (!m) throw new Error(`defaults.md: cannot parse row: ${row}`);
    const [, key, json] = m;
    if (key in out) throw new Error(`defaults.md: duplicate key ${key}`);
    try {
      out[key] = JSON.parse(json);
    } catch (e) {
      throw new Error(`defaults.md: bad JSON for ${key}: ${json}`);
    }
  }
  return out;
}

function readPresets() {
  const dir = join(root, "spec/presets");
  const presets = {};
  for (const f of readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
    const name = f.replace(/\.json$/, "");
    const data = JSON.parse(readFileSync(join(dir, f), "utf8"));
    delete data.$comment;
    presets[name] = data;
  }
  return presets;
}

// Canonical JSON: keys in insertion order as authored (stable), no whitespace.
const json = (v) => JSON.stringify(v);

function readSchema(file) {
  return JSON.parse(readFileSync(join(root, "spec/schema", file), "utf8"));
}

function rustSpecData(defaults, presets) {
  const presetNames = Object.keys(presets);
  const lines = [];
  lines.push(`// ${banner}`);
  lines.push("//! Spec data (defaults table and presets) as embedded JSON.");
  lines.push("");
  lines.push(`/// Schema version implemented.`);
  lines.push(`pub const SCHEMA_VERSION: &str = "1";`);
  lines.push("");
  lines.push("/// Flat map from dotted key to JSON default (spec/defaults.md).");
  lines.push(`pub const DEFAULTS_JSON: &str = r##"${json(defaults)}"##;`);
  lines.push("");
  lines.push("/// Presets (spec/presets/*.json) as (name, JSON).");
  lines.push("pub const PRESETS: &[(&str, &str)] = &[");
  for (const n of presetNames) lines.push(`    ("${n}", r##"${json(presets[n])}"##),`);
  lines.push("];");
  lines.push("");
  lines.push("/// spec/schema/problem.v1.json (minified), interpreted by the validator.");
  lines.push(`pub const PROBLEM_SCHEMA_JSON: &str = r##"${json(readSchema("problem.v1.json"))}"##;`);
  lines.push("");
  return lines.join("\n");
}

function tsSpecData(defaults, presets) {
  const lines = [];
  lines.push(`// ${banner}`);
  lines.push("/** Schema version implemented. */");
  lines.push(`export const SCHEMA_VERSION = "1";`);
  lines.push("");
  lines.push("/** Flat map from dotted key to JSON default (spec/defaults.md). */");
  lines.push(`export const DEFAULTS: Readonly<Record<string, unknown>> = ${JSON.stringify(defaults, null, 2)};`);
  lines.push("");
  lines.push("/** Presets (spec/presets/*.json). */");
  lines.push(`export const PRESETS: Readonly<Record<string, PresetData>> = ${JSON.stringify(presets, null, 2)};`);
  lines.push("");
  lines.push("/** spec/schema/problem.v1.json, interpreted by the validator. */");
  lines.push(`export const PROBLEM_SCHEMA: Readonly<Record<string, unknown>> = ${JSON.stringify(readSchema("problem.v1.json"))};`);
  lines.push("");
  lines.push("export interface PresetData {");
  lines.push("  description: string;");
  lines.push("  options: Record<string, unknown>;");
  lines.push("  svg_classes: { selector: string; class: string }[];");
  lines.push("  auto?: { crowded_fraction: number; crowded_models: string[] };");
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

function tsFonts() {
  const fonts = [
    ["NOTO_SANS_REGULAR", "fonts/NotoSans-Regular.metrics.ttf", 400],
    ["NOTO_SANS_BOLD", "fonts/NotoSans-Bold.metrics.ttf", 700],
  ];
  const lines = [`// ${banner}`, "// Noto Sans 2.015 subset, outlines removed (metrics only). SIL OFL 1.1, see fonts/OFL.txt.", ""];
  for (const [name, path, weight] of fonts) {
    const b64 = readFileSync(join(root, path)).toString("base64");
    lines.push(`/** ${path} (weight ${weight}), base64. */`);
    lines.push(`export const ${name}_BASE64 =`);
    // split into 120-char chunks to keep editors happy
    const chunks = b64.match(/.{1,120}/g) ?? [];
    lines.push(chunks.map((c) => `  "${c}"`).join(" +\n") + ";");
    lines.push("");
  }
  return lines.join("\n");
}

/**
 * json-schema-to-typescript understands draft-07 tuples (`items: [...]`) but not 2020-12
 * `prefixItems`, which it types as `[unknown, unknown]`. Rewrite them (types only; the
 * validators read the real schema).
 */
function draft07Tuples(node) {
  if (Array.isArray(node)) return node.map(draft07Tuples);
  if (node === null || typeof node !== "object") return node;
  const out = {};
  for (const [k, v] of Object.entries(node)) out[k] = draft07Tuples(v);
  if (Array.isArray(out.prefixItems)) {
    const rest = out.items;
    out.items = out.prefixItems;
    delete out.prefixItems;
    const closed = rest === false || (out.maxItems !== undefined && out.maxItems === out.items.length);
    out.additionalItems = closed ? false : rest ?? true;
  }
  return out;
}

async function tsTypes() {
  const require = createRequire(join(root, "package.json"));
  const { compile } = require("json-schema-to-typescript");
  const out = {};
  for (const [name, file] of [["problem", "problem.v1.json"], ["result", "result.v1.json"]]) {
    const schema = draft07Tuples(JSON.parse(readFileSync(join(root, "spec/schema", file), "utf8")));
    if (name === "problem") {
      // TypeScript requires named properties to match the index signature; widen the
      // index type of avoid.label so `own_mark` (partial:f) type-checks. Validation is
      // unaffected (it is hand-written against the real schema).
      const label = schema.$defs.avoid.properties.label;
      label.additionalProperties = {
        anyOf: [{ $ref: "#/$defs/avoidValue" }, { $ref: "#/$defs/ownMarkValue" }],
      };
    }
    const ts = await compile(schema, schema.title, {
      bannerComment: `/* ${banner} (spec/schema/${file}) */`,
      additionalProperties: false,
      unknownAny: true,
      strictIndexSignatures: true,
      style: { singleQuote: false, semi: true, printWidth: 100 },
      cwd: join(root, "spec/schema"),
    });
    out[name] = ts;
  }
  return out;
}

function emit(rel, content) {
  const path = join(root, rel);
  const old = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (old === content) return false;
  if (check) {
    console.error(`stale: ${rel}`);
    return true;
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
  console.log(`wrote ${rel}`);
  return true;
}

// Published crates cannot include files outside their directory, so la-text embeds copies
// of the metrics fonts (and their license) from rust/crates/la-text/assets/, and the CLI
// the fonts with outlines (for PNG rendering) from rust/crates/la-cli/assets/.
function copyRustFonts() {
  let changed = false;
  const copies = [
    ...["NotoSans-Regular.metrics.ttf", "NotoSans-Bold.metrics.ttf", "OFL.txt"].map((f) => [f, "la-text"]),
    ...["NotoSans-Regular.ttf", "NotoSans-Bold.ttf", "OFL.txt"].map((f) => [f, "la-cli"]),
  ];
  for (const [file, crate] of copies) {
    const rel = `rust/crates/${crate}/assets/${file}`;
    const source = readFileSync(join(root, "fonts", file));
    const target = join(root, rel);
    if (existsSync(target) && readFileSync(target).equals(source)) continue;
    changed = true;
    if (check) {
      console.error(`stale: ${rel}`);
      continue;
    }
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, source);
    console.log(`wrote ${rel}`);
  }
  return changed;
}

const defaults = parseDefaultsTable(readFileSync(join(root, "spec/defaults.md"), "utf8"));
const presets = readPresets();
let stale = false;
stale = emit("rust/crates/la-core/src/generated/spec_data.rs", rustSpecData(defaults, presets)) || stale;
stale = emit("ts/packages/core/src/generated/spec-data.ts", tsSpecData(defaults, presets)) || stale;
stale = emit("ts/packages/text/src/generated/fonts.ts", tsFonts()) || stale;
stale = copyRustFonts() || stale;
const types = await tsTypes();
stale = emit("ts/packages/core/src/generated/problem.ts", types.problem) || stale;
stale = emit("ts/packages/core/src/generated/result.ts", types.result) || stale;
if (check && stale) {
  console.error("Generated files are stale. Run: node tools/codegen.mjs");
  process.exit(1);
}
if (!stale) console.log("codegen: up to date");
