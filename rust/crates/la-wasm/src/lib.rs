//! WebAssembly binding of Label Anything (wasm-bindgen, `wasm32-unknown-unknown`).
//!
//! The npm package `@label-anything/wasm` (`ts/packages/wasm-adapter`) wraps these raw
//! exports into the `LabelAnythingApi` of `@label-anything/core`; applications should use
//! the package. Contract of the raw exports:
//!
//! * `place(problemJson, options)` returns the result JSON text (an object) or, when the
//!   problem is invalid or cannot be prepared, the list of errors (a JSON array, the
//!   `errors` of a `PlaceError`). `options` is a `PlaceOptions` object: the callbacks
//!   `measure`, `cost`, `progress`, `readFile`, the `signal` and the `raster` pixels;
//!   `priority` is evaluated by the wrapper before the call. The first exception thrown
//!   by a callback stops all further callbacks and is rethrown unchanged; wrong option
//!   types throw a `TypeError` (a wrong pixel count a `RangeError`). If the signal is
//!   already aborted, the solve stops after the greedy phase (`solver.strategy` greedy).
//! * `validate(problemJson)` returns the report JSON `{valid, errors, warnings}`.
//! * `renderSvg(problemJson, resultJson)` returns the debug SVG, or an error list (a JSON
//!   array) when a JSON text is invalid.
//! * `version()` and `features()` (the optional parts compiled in: `shaping`, `decode`,
//!   `svg`).
//! * `callDepth()`: the number of `place`/`validate`/`renderSvg` calls executing. The
//!   calls decrement it on every normal return, including errors and rethrown callback
//!   exceptions. A Rust panic (turned into an `Error` by the panic hook) or a trap (out
//!   of memory, stack overflow) leaves it raised, which tells the wrapper to replace the
//!   instance (`__wbg_reset_state`, generated by `wasm-bindgen
//!   --experimental-reset-state-function`).

mod env;
mod js;

use env::JsEnv;
use label_anything::{Env, Issue};
use serde_json::Value;
use std::sync::atomic::{AtomicU32, Ordering};
use wasm_bindgen::prelude::*;

static DEPTH: AtomicU32 = AtomicU32::new(0);

/// Runs `f` inside `callDepth()` accounting. The decrement is deliberately not a drop
/// guard: it must be skipped when `f` never returns.
fn counted<T>(f: impl FnOnce() -> T) -> T {
    DEPTH.fetch_add(1, Ordering::Relaxed);
    let r = f();
    DEPTH.fetch_sub(1, Ordering::Relaxed);
    r
}

/// Instance start: install the panic hook. A panic aborts on wasm32 (there is no
/// unwinding); the hook throws a JavaScript `Error` with the panic message instead of
/// letting the call end in an anonymous `RuntimeError: unreachable`.
#[wasm_bindgen(start)]
fn start() {
    std::panic::set_hook(Box::new(|info| {
        wasm_bindgen::throw_str(&format!(
            "label-anything: internal error (Rust panic): {info}"
        ))
    }));
}

fn issues_json(errors: &[Issue]) -> String {
    serde_json::to_string(errors).unwrap_or_else(|_| {
        r#"[{"pointer":"","code":"internal","message":"cannot serialize the errors"}]"#.into()
    })
}

fn parse_error(what: &str, e: serde_json::Error) -> String {
    issues_json(&[Issue::new("", "parse", format!("invalid {what}JSON: {e}"))])
}

/// Stop after the greedy phase (an already aborted signal).
fn force_greedy(problem: &mut Value) {
    if let Some(obj) = problem.as_object_mut() {
        let solver = obj
            .entry("solver")
            .or_insert_with(|| Value::Object(Default::default()));
        if let Some(s) = solver.as_object_mut() {
            s.insert("strategy".into(), Value::from("greedy"));
        }
    }
}

fn place_impl(problem_json: &str, options: &JsValue) -> Result<String, JsValue> {
    let env = JsEnv::from_options(options)?;
    let mut problem: Value = match serde_json::from_str(problem_json) {
        Ok(v) => v,
        Err(e) => return Ok(parse_error("", e)),
    };
    let report = label_anything::validate(&problem);
    if !report.valid {
        return Ok(issues_json(&report.errors));
    }
    let aborted = env.cancelled();
    if let Some(e) = env.take_error() {
        return Err(e);
    }
    if aborted {
        force_greedy(&mut problem);
    }
    let out = label_anything::place_validated(&problem, &env, report);
    if let Some(e) = env.take_error() {
        return Err(e);
    }
    Ok(match out {
        Ok(result) => result.to_string(),
        Err(e) => issues_json(&e.errors),
    })
}

/// Solve a problem (see the crate documentation for the contract).
#[wasm_bindgen]
pub fn place(problem_json: &str, options: &JsValue) -> Result<String, JsValue> {
    counted(|| place_impl(problem_json, options))
}

/// Validate a problem: the report JSON `{valid, errors, warnings}`.
#[wasm_bindgen]
pub fn validate(problem_json: &str) -> String {
    counted(|| {
        let report = la_core::validate::validate_str(problem_json);
        serde_json::to_string(&report).unwrap_or_else(|_| {
            r#"{"valid":false,"errors":[{"pointer":"","code":"internal","message":"cannot serialize the report"}],"warnings":[]}"#.into()
        })
    })
}

/// The debug SVG overlay of a problem and a result (an error list for invalid JSON).
#[wasm_bindgen(js_name = renderSvg)]
pub fn render_svg(problem_json: &str, result_json: &str) -> String {
    counted(|| {
        let problem: Value = match serde_json::from_str(problem_json) {
            Ok(v) => v,
            Err(e) => return parse_error("problem ", e),
        };
        let result: Value = match serde_json::from_str(result_json) {
            Ok(v) => v,
            Err(e) => return parse_error("result ", e),
        };
        label_anything::render_svg(&problem, &result, &JsEnv::empty())
    })
}

/// Version of the Rust core.
#[wasm_bindgen]
pub fn version() -> String {
    label_anything::VERSION.to_string()
}

/// Optional parts compiled into this build.
#[wasm_bindgen]
pub fn features() -> Vec<String> {
    // la-core enables la-text's default features, so full shaping (rustybuzz) is always in
    let mut f = vec!["shaping".to_string()];
    if cfg!(feature = "decode") {
        f.push("decode".into());
    }
    if label_anything::svg_backend().is_some() {
        f.push("svg".into());
    }
    f
}

/// Number of raw calls currently executing (see the crate documentation).
#[wasm_bindgen(js_name = callDepth)]
pub fn call_depth() -> u32 {
    DEPTH.load(Ordering::Relaxed)
}

/// Test hook: panics inside a counted call (checks the panic hook and the instance reset).
#[doc(hidden)]
#[wasm_bindgen(js_name = __testPanic)]
pub fn test_panic(message: &str) {
    counted(|| panic!("{message}"))
}

/// Test hook: traps without a panic (like an out-of-memory abort).
#[doc(hidden)]
#[wasm_bindgen(js_name = __testTrap)]
pub fn test_trap() {
    counted(|| {
        #[cfg(target_arch = "wasm32")]
        core::arch::wasm32::unreachable();
        #[cfg(not(target_arch = "wasm32"))]
        std::process::abort();
    })
}
