//! Colour helpers (spec §4.6): hex colours, deterministic OKLab, background estimation.
//!
//! Everything here uses only IEEE-754 `+ − × ÷ sqrt` on `f64` in a fixed evaluation order,
//! so the TypeScript implementation produces the same bits.

use crate::rgba::Rgba;
use crate::srgb_lut::SRGB_TO_LINEAR;

/// Parses `#rgb` or `#rrggbb` (hex digits in either case). `#rgb` expands each digit
/// `d` to `dd`. Anything else (no `#`, other lengths, whitespace) is `None`.
///
/// ```
/// use label_anything_raster::parse_hex_color;
/// assert_eq!(parse_hex_color("#1a2B3c"), Some([0x1a, 0x2b, 0x3c]));
/// assert_eq!(parse_hex_color("#fA0"), Some([0xff, 0xaa, 0x00]));
/// assert_eq!(parse_hex_color("fa0"), None);
/// ```
pub fn parse_hex_color(s: &str) -> Option<[u8; 3]> {
    fn hex(c: u8) -> Option<u8> {
        match c {
            b'0'..=b'9' => Some(c - b'0'),
            b'a'..=b'f' => Some(c - b'a' + 10),
            b'A'..=b'F' => Some(c - b'A' + 10),
            _ => None,
        }
    }
    let digits = s.as_bytes().strip_prefix(b"#")?;
    match digits.len() {
        3 => Some([
            hex(digits[0])? * 17,
            hex(digits[1])? * 17,
            hex(digits[2])? * 17,
        ]),
        6 => Some([
            hex(digits[0])? << 4 | hex(digits[1])?,
            hex(digits[2])? << 4 | hex(digits[3])?,
            hex(digits[4])? << 4 | hex(digits[5])?,
        ]),
        _ => None,
    }
}

/// Coefficients of the initial guess `((C3·m + C2)·m + C1)·m + C0 ≈ ∛m` on `[1/8, 1)`
/// (max. relative error 0.52 %).
const CBRT_C0: f64 = 0.3408421562;
const CBRT_C1: f64 = 1.458110692;
const CBRT_C2: f64 = -1.385919418;
const CBRT_C3: f64 = 0.5921815819;

/// Deterministic cube root using only `+ − × ÷` (spec §4.6; identical in TypeScript).
///
/// 1. `±0`, `±∞` and NaN are returned unchanged; negative `x` gives `−cbrt(−x)`.
/// 2. Exact range reduction: `x = m · 8^k` with `m ∈ [1/8, 1)` (multiplications by 8 and
///    1/8 are exact), result scale `s = 2^k`.
/// 3. Initial guess `y = ((C3·m + C2)·m + C1)·m + C0`.
/// 4. Three Newton steps `y = y − (y·y·y − m) / (3·y·y)` (left to right: `(y·y)·y`,
///    `(3·y)·y`).
/// 5. Result `y · s` (exact).
///
/// Within 1 ulp of the correctly rounded cube root (tested).
#[inline(always)]
pub(crate) fn cbrt(x: f64) -> f64 {
    if x == 0.0 || !x.is_finite() {
        return x;
    }
    let (m, s) = reduce_cbrt(x.abs());
    let mut y = ((CBRT_C3 * m + CBRT_C2) * m + CBRT_C1) * m + CBRT_C0;
    y -= (y * y * y - m) / (3.0 * y * y);
    y -= (y * y * y - m) / (3.0 * y * y);
    y -= (y * y * y - m) / (3.0 * y * y);
    let r = y * s;
    if x < 0.0 {
        -r
    } else {
        r
    }
}

/// The exact range reduction of [`cbrt`] for finite `x > 0`: the unique `m = x · 8^j ∈
/// [1/8, 1)` and `s = 2^−j`. Normal inputs read `j` off the exponent (no data-dependent
/// loop); this is bit-identical to scaling by 8 or 1/8 step by step (all products are
/// exact), which [`reduce_cbrt_stepwise`] does and the TypeScript code does.
#[inline(always)]
fn reduce_cbrt(x: f64) -> (f64, f64) {
    let e = ((x.to_bits() >> 52) & 0x7ff) as i32 - 1023; // x ∈ [2^e, 2^(e+1)) if normal
    if !(-1000..=1000).contains(&e) {
        return reduce_cbrt_stepwise(x);
    }
    let j = (-e - 1).div_euclid(3);
    let pow2 = |k: i32| f64::from_bits(((k + 1023) as u64) << 52);
    (x * pow2(3 * j), pow2(-j))
}

/// Step-by-step version of [`reduce_cbrt`] (used for subnormal and huge inputs).
fn reduce_cbrt_stepwise(x: f64) -> (f64, f64) {
    let mut m = x;
    let mut s = 1.0;
    while m < 0.125 {
        m *= 8.0;
        s *= 0.5;
    }
    while m >= 1.0 {
        m *= 0.125;
        s *= 2.0;
    }
    (m, s)
}

/// Converts an 8-bit sRGB colour to OKLab `[L, a, b]` (Björn Ottosson's published
/// matrices), deterministically:
///
/// * `r, g, b` = `SRGB_TO_LINEAR[·]`, a 256-entry table of exactly rounded constants
///   generated by `tools/raster/gen_srgb_lut.py`;
/// * `l = 0.4122214708·r + 0.5363325363·g + 0.0514459929·b`,
///   `m = 0.2119034982·r + 0.6806995451·g + 0.1073969566·b`,
///   `s = 0.0883024619·r + 0.2817188376·g + 0.6299787005·b` (each summed left to right);
/// * `l' = cbrt(l)` etc. with the deterministic cube root documented in the spec;
/// * `L = 0.2104542553·l' + 0.7936177850·m' − 0.0040720468·s'`,
///   `a = 1.9779984951·l' − 2.4285922050·m' + 0.4505937099·s'`,
///   `b = 0.0259040371·l' + 0.7827717662·m' − 0.8086757660·s'`.
#[inline]
pub fn srgb_to_oklab(rgb: [u8; 3]) -> [f64; 3] {
    let r = SRGB_TO_LINEAR[rgb[0] as usize];
    let g = SRGB_TO_LINEAR[rgb[1] as usize];
    let b = SRGB_TO_LINEAR[rgb[2] as usize];
    let l = 0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b;
    let m = 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b;
    let s = 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b;
    let l_ = cbrt(l);
    let m_ = cbrt(m);
    let s_ = cbrt(s);
    [
        0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_,
        1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_,
        0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_,
    ]
}

/// Euclidean OKLab distance `sqrt((ΔL·ΔL + Δa·Δa) + Δb·Δb)`.
#[inline]
pub(crate) fn oklab_distance(p: &[f64; 3], q: &[f64; 3]) -> f64 {
    let dl = p[0] - q[0];
    let da = p[1] - q[1];
    let db = p[2] - q[2];
    (dl * dl + da * da + db * db).sqrt()
}

/// Composites one 8-bit channel over a background channel by alpha `a` and rounds to
/// 8 bits: `floor((c·a + bg·(255 − a)) / 255 + 1/2)`, computed exactly as
/// `(c·a + bg·(255 − a) + 127) div 255` (there are no exact halves).
#[inline]
pub(crate) fn composite(c: u8, bg: u8, a: u8) -> u8 {
    let a = u32::from(a);
    ((u32::from(c) * a + u32::from(bg) * (255 - a) + 127) / 255) as u8
}

/// Estimates the background colour of a raster (spec §4.6):
///
/// the most frequent colour among the border pixels (first and last row and column, each
/// pixel counted once), with colours quantized to 5 bits per channel (`c >> 3`); pixels
/// with alpha < 128 are skipped; ties go to the smallest packed value
/// `(r5 << 10) | (g5 << 5) | b5`. The winner is expanded back to 8 bits as
/// `(q << 3) | (q >> 2)`. Without any qualifying border pixel (or for an invalid
/// [`Rgba`]) the background is white.
pub fn estimate_background(img: &Rgba) -> [u8; 3] {
    const WHITE: [u8; 3] = [255, 255, 255];
    if !img.is_valid() {
        return WHITE;
    }
    let w = img.width as usize;
    let h = img.height as usize;
    let mut hist = vec![0u32; 1 << 15];
    let mut counted = 0usize;
    let mut count = |x: usize, y: usize| {
        let i = (y * w + x) * 4;
        let p = &img.data[i..i + 4];
        if p[3] >= 128 {
            let key = (usize::from(p[0] >> 3) << 10)
                | (usize::from(p[1] >> 3) << 5)
                | usize::from(p[2] >> 3);
            hist[key] += 1;
            counted += 1;
        }
    };
    for x in 0..w {
        count(x, 0);
    }
    if h > 1 {
        for x in 0..w {
            count(x, h - 1);
        }
    }
    for y in 1..h.saturating_sub(1) {
        count(0, y);
        if w > 1 {
            count(w - 1, y);
        }
    }
    if counted == 0 {
        return WHITE;
    }
    let mut best = 0usize;
    for (key, &n) in hist.iter().enumerate() {
        if n > hist[best] {
            best = key;
        }
    }
    let expand = |q: usize| ((q << 3) | (q >> 2)) as u8;
    [
        expand(best >> 10),
        expand((best >> 5) & 31),
        expand(best & 31),
    ]
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ulps(a: f64, b: f64) -> f64 {
        (a - b).abs() / f64::EPSILON / b.abs().max(f64::MIN_POSITIVE)
    }

    #[test]
    fn cbrt_is_accurate_and_handles_specials() {
        assert_eq!(cbrt(0.0).to_bits(), 0.0f64.to_bits());
        assert_eq!(cbrt(-0.0).to_bits(), (-0.0f64).to_bits());
        assert!(cbrt(f64::NAN).is_nan());
        assert_eq!(cbrt(f64::INFINITY), f64::INFINITY);
        assert_eq!(cbrt(-8.0), -2.0);
        assert_eq!(cbrt(1.0), 1.0);
        assert_eq!(cbrt(0.125), 0.5);
        // Deterministic LCG over a wide range, compared with libm (test-only).
        let mut state = 0x2545F4914F6CDD1Du64;
        for _ in 0..200_000 {
            state = state
                .wrapping_mul(6364136223846793005)
                .wrapping_add(1442695040888963407);
            let u = (state >> 11) as f64 / (1u64 << 53) as f64;
            let x = (u * 60.0 - 40.0).exp();
            let e = ulps(cbrt(x), x.cbrt());
            assert!(e <= 2.0, "cbrt({x}) off by {e} ulps");
        }
        for x in [f64::MIN_POSITIVE, 5e-324, 1e-300, 1e300, f64::MAX] {
            assert!(ulps(cbrt(x), x.cbrt()) <= 2.0, "{x}");
        }
    }

    #[test]
    fn range_reduction_matches_stepwise() {
        let mut state = 0x9E37_79B9_7F4A_7C15u64;
        let check = |x: f64| {
            let (m, s) = reduce_cbrt(x);
            let (m2, s2) = reduce_cbrt_stepwise(x);
            assert_eq!(
                (m.to_bits(), s.to_bits()),
                (m2.to_bits(), s2.to_bits()),
                "{x:e}"
            );
            assert!((0.125..1.0).contains(&m), "{x:e}");
        };
        for _ in 0..1_000_000 {
            state = state
                .wrapping_mul(6364136223846793005)
                .wrapping_add(1442695040888963407);
            // Random positive finite doubles over the whole exponent range.
            let bits = (state >> 1) & 0x7FEF_FFFF_FFFF_FFFF;
            check(f64::from_bits(bits.max(1)));
        }
        for k in -1074..1024 {
            let p = 2f64.powi(k);
            for x in [p, p * 1.5, p * (2.0 - f64::EPSILON)] {
                if x.is_finite() && x > 0.0 {
                    check(x);
                }
            }
        }
        check(f64::MAX);
        check(f64::MIN_POSITIVE);
        check(5e-324);
    }

    #[test]
    fn oklab_matches_reference() {
        // Reference values: the same matrices with libm cbrt (test-only).
        let reference = |rgb: [u8; 3]| {
            let lin = |c: u8| {
                let v = f64::from(c) / 255.0;
                if v <= 0.04045 {
                    v / 12.92
                } else {
                    ((v + 0.055) / 1.055).powf(2.4)
                }
            };
            let (r, g, b) = (lin(rgb[0]), lin(rgb[1]), lin(rgb[2]));
            let l = (0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b).cbrt();
            let m = (0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b).cbrt();
            let s = (0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b).cbrt();
            [
                0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s,
                1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s,
                0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s,
            ]
        };
        for r in (0..=255).step_by(5) {
            for g in (0..=255).step_by(15) {
                for b in (0..=255).step_by(17) {
                    let ours = srgb_to_oklab([r as u8, g as u8, b as u8]);
                    let theirs = reference([r as u8, g as u8, b as u8]);
                    for k in 0..3 {
                        assert!((ours[k] - theirs[k]).abs() < 1e-12, "{r},{g},{b}");
                    }
                }
            }
        }
        // The published 10-digit M2 rows sum to 0.9999999935, 0 and 3.73e-8.
        let white = srgb_to_oklab([255, 255, 255]);
        assert!((white[0] - 1.0).abs() < 1e-8 && white[1].abs() < 1e-8 && white[2].abs() < 1e-7);
        assert_eq!(srgb_to_oklab([0, 0, 0]), [0.0, 0.0, 0.0]);
        // Ottosson's published value for sRGB red: L 0.627955, a 0.224863, b 0.125846.
        let red = srgb_to_oklab([255, 0, 0]);
        assert!((red[0] - 0.627955).abs() < 1e-6);
        assert!((red[1] - 0.224863).abs() < 1e-6);
        assert!((red[2] - 0.125846).abs() < 1e-6);
    }

    #[test]
    fn hex_colors() {
        assert_eq!(parse_hex_color("#000"), Some([0, 0, 0]));
        assert_eq!(parse_hex_color("#FFFFFF"), Some([255, 255, 255]));
        assert_eq!(parse_hex_color("#abc"), Some([0xaa, 0xbb, 0xcc]));
        for bad in [
            "", "#", "#ab", "#abcd", "#abcde", "#abcdefa", "#ggg", " #abc", "#abc ", "abc",
        ] {
            assert_eq!(parse_hex_color(bad), None, "{bad:?}");
        }
    }

    #[test]
    fn composite_rounds_to_nearest() {
        for c in [0u8, 1, 127, 128, 254, 255] {
            for bg in [0u8, 255, 77] {
                for a in 0..=255u8 {
                    let exact = (f64::from(c) * f64::from(a)
                        + f64::from(bg) * (255.0 - f64::from(a)))
                        / 255.0;
                    assert_eq!(composite(c, bg, a), (exact + 0.5).floor() as u8);
                }
            }
        }
    }

    fn img(w: u32, h: u32, f: impl Fn(u32, u32) -> [u8; 4]) -> Rgba {
        let mut data = Vec::new();
        for y in 0..h {
            for x in 0..w {
                data.extend_from_slice(&f(x, y));
            }
        }
        Rgba::new(w, h, data).unwrap()
    }

    #[test]
    fn background_estimation() {
        // Mostly-white border with a black interior.
        let a = img(5, 4, |x, y| {
            if x == 0 || y == 0 || x == 4 || y == 3 {
                [250, 251, 252, 255]
            } else {
                [0, 0, 0, 255]
            }
        });
        assert_eq!(estimate_background(&a), [255, 255, 255]);
        // Tie between red and blue (4 border pixels each) -> smaller packed value (blue).
        let b = img(4, 2, |x, _| {
            if x < 2 {
                [255, 0, 0, 255]
            } else {
                [0, 0, 255, 255]
            }
        });
        assert_eq!(estimate_background(&b), [0, 0, 255]);
        // Transparent border -> white; 1x1 and single rows/columns count pixels once.
        let c = img(3, 3, |_, _| [10, 20, 30, 127]);
        assert_eq!(estimate_background(&c), [255, 255, 255]);
        let d = img(1, 1, |_, _| [10, 20, 30, 128]);
        assert_eq!(estimate_background(&d), [8, 16, 24]);
        let e = img(1, 3, |_, y| {
            if y == 1 {
                [0, 0, 0, 255]
            } else {
                [255, 255, 255, 255]
            }
        });
        assert_eq!(estimate_background(&e), [255, 255, 255]);
        assert_eq!(estimate_background(&Rgba::default()), [255, 255, 255]);
    }
}
