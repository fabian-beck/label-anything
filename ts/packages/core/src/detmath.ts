/** ln(x) as a double-double in rH, rL, for finite x > 0. */
function lnDD(x: number): void {
  let k = 0;
  if (x < MIN_POSITIVE) {
    x *= TWO54;
    k = -54;
  }
  const hx = hiWord(x);
  const lx = loWord(x);
  k += (hx >>> 20) - 1023;
  let m = fromWords(((hx & 0x000fffff) | 0x3ff00000) >>> 0, lx);
  if (m > SQRT2) {
    m *= 0.5;
    k += 1;
  }
  const j = (m * 64.0 + 0.5) | 0;
  const c = j * 0.015625;
  const d = m - c;
  twoSum(m, c);
  const ah = rH;
  const al = rL;
  const sh = d / ah;
  twoProd(sh, ah);
  const p = rH;
  const pe = rL;
  const sl = (((d - p) - pe) - sh * al) / ah;
  const z = sh * sh;
  const tail = sh * z * horner(z, LN_POLY);
  const kf = k;
  const i = j - LN_TAB_J0;
  twoSum(kf * LN2_HI, LN_TAB_HI[i] as number);
  const h1 = rH;
  const e1 = rL;
  twoSum(h1, 2.0 * sh);
  const h2 = rH;
  const e2 = rL;
  const lo = (e1 + e2) + (((kf * LN2_LO + (LN_TAB_LO[i] as number)) + 2.0 * sl) + tail);
  fastTwoSum(h2, lo);
}

/** Natural logarithm. ln(±0) = -Infinity, ln(x < 0) = NaN, ln(Infinity) = Infinity. */
export function ln(x: number): number {
  if (x > 0.0) {
    if (x === Infinity) return x;
    lnDD(x);
    return rH;
  }
  return x === 0.0 ? -Infinity : NaN;
}

/** ln(1 + x), accurate for tiny x. ln1p(-1) = -Infinity, ln1p(x < -1) = NaN, ln1p(±0) = ±0. */
export function ln1p(x: number): number {
  if (x > -1.0) {
    if (x === Infinity) return x;
    const ax = Math.abs(x);
    if (ax < TWO_M54) return x;
    if (ax < TWO_M20) return x + x * x * horner(x, LN1P_POLY);
    twoSum(1.0, x);
    const u = rH;
    const c = rL;
    lnDD(u);
    return rH + (rL + c / u);
  }
  return x === -1.0 ? -Infinity : NaN;
}

