/** Rounds toward zero. Exact; trunc(-0.5) = -0. */
export function trunc(x: number): number {
  const ax = Math.abs(x);
  if (ax !== ax || ax >= TWO52) return ax !== ax ? NaN : x;
  let r = (ax + TWO52) - TWO52;
  if (r > ax) r -= 1.0;
  return signBit(x) ? -r : r;
}

/** Largest integer ≤ x. Exact; floor(-0) = -0. */
export function floor(x: number): number {
  const t = trunc(x);
  return t > x ? t - 1.0 : t;
}

/** Smallest integer ≥ x. Exact; ceil(-0.5) = -0. */
export function ceil(x: number): number {
  const t = trunc(x);
  return t < x ? t + 1.0 : t;
}

/**
 * Nearest integer, halves rounded away from zero (C `round`, NOT `Math.round`):
 * roundHalfAway(-2.5) = -3, roundHalfAway(0.49999999999999994) = 0.
 */
export function roundHalfAway(x: number): number {
  const ax = Math.abs(x);
  if (ax !== ax || ax >= TWO52) return ax !== ax ? NaN : x;
  const t = trunc(ax);
  const r = ax - t >= 0.5 ? t + 1.0 : t;
  return signBit(x) ? -r : r;
}

/** IEEE-754 square root (correctly rounded; listed for completeness). */
export function sqrt(x: number): number {
  return Math.sqrt(x);
}

