/** e^(x + xt) for EXP_UNDERFLOW ≤ x ≤ EXP_OVERFLOW and a small tail xt. */
function expCore(x: number, xt: number): number {
  if (Math.abs(x) < TWO_M54) return 1.0 + x;
  const k = floor(x * INV_LN2 + 0.5);
  const hi = x - k * LN2_HI;
  const lo = k * LN2_LO - xt;
  twoSum(hi, -lo);
  const r = rH;
  const rl = rL;
  twoProd(r, r);
  const q = rH;
  const qe = rL + 2.0 * r * rl;
  fastTwoSum(1.0, hi);
  const s = rH;
  const se = rL;
  fastTwoSum(s, 0.5 * q);
  const s2 = rH;
  const s2e = rL;
  const p = r * q * horner(r, EXP_POLY);
  const y = s2 + (((se + s2e) + (0.5 * qe - lo)) + p);
  return scalbn(y, k);
}

/** e^x. Overflow → Infinity, underflow → +0 (gradual for subnormal results). */
export function exp(x: number): number {
  if (x !== x) return NaN;
  if (x > EXP_OVERFLOW) return Infinity;
  if (x < EXP_UNDERFLOW) return 0.0;
  return expCore(x, 0.0);
}

/** ax^n for finite ax > 0 and 1 ≤ |n| ≤ 2^30: double-double repeated squaring. */
function powi(ax: number, n: number): number {
  const e = ilogb(ax);
  let bh = scalbn(ax, -e);
  let bl = 0.0;
  let be = e;
  let rh = 1.0;
  let rl = 0.0;
  let re = 0;
  let k = Math.abs(n);
  for (;;) {
    if ((k & 1) === 1) {
      ddMul(rh, rl, bh, bl);
      rh = rH;
      rl = rL;
      re += be;
      while (rh >= 2.0) {
        rh *= 0.5;
        rl *= 0.5;
        re += 1;
      }
      while (rh < 1.0) {
        rh *= 2.0;
        rl *= 2.0;
        re -= 1;
      }
    }
    k >>>= 1;
    if (k === 0) break;
    ddMul(bh, bl, bh, bl);
    bh = rH;
    bl = rL;
    be *= 2;
    while (bh >= 2.0) {
      bh *= 0.5;
      bl *= 0.5;
      be += 1;
    }
    while (bh < 1.0) {
      bh *= 2.0;
      bl *= 2.0;
      be -= 1;
    }
  }
  if (n < 0) {
    ddRecip(rh, rl);
    rh = rH;
    rl = rL;
    re = -re;
    while (rh >= 2.0) {
      rh *= 0.5;
      rl *= 0.5;
      re += 1;
    }
    while (rh < 1.0) {
      rh *= 2.0;
      rl *= 2.0;
      re -= 1;
    }
  }
  if (re > 2100) return Infinity;
  if (re < -2200) return 0.0;
  return scalbn(rh + rl, re);
}

/** ax^y = e^(y·ln ax) for finite ax > 0 and finite y, in double-double. */
function powPos(ax: number, y: number): number {
  lnDD(ax);
  const lh = rH;
  const ll = rL;
  const t = y * lh;
  if (t > EXP_OVERFLOW) return Infinity;
  if (t < EXP_UNDERFLOW) return 0.0;
  twoProd(y, lh);
  const p = rH;
  const pe = rL;
  fastTwoSum(p, pe + y * ll);
  return expCore(rH, rL);
}

/**
 * x^y with the special cases of C99 Annex F (which differ from `Math.pow` for
 * pow(1, NaN) = 1 and pow(±1, ±Infinity) = 1). Integer y with |y| ≤ 2^30 uses
 * double-double repeated squaring (negative bases allowed); otherwise e^(y·ln|x|).
 */
export function pow(x: number, y: number): number {
  if (y === 0.0 || x === 1.0) return 1.0;
  if (x !== x || y !== y) return NaN;
  const ax = Math.abs(x);
  if (y === Infinity || y === -Infinity) {
    if (ax === 1.0) return 1.0;
    return ax > 1.0 === y > 0.0 ? Infinity : 0.0;
  }
  const yInt = floor(y) === y;
  const yOdd = yInt && Math.abs(y) < TWO53 && floor(y * 0.5) !== y * 0.5;
  const neg = signBit(x) && yOdd;
  if (ax === 0.0 || ax === Infinity) {
    const r = (ax === 0.0) === y < 0.0 ? Infinity : 0.0;
    return neg ? -r : r;
  }
  if (x < 0.0 && !yInt) return NaN;
  const r = yInt && Math.abs(y) <= POWI_MAX ? powi(ax, y) : powPos(ax, y);
  return neg ? -r : r;
}

/** Real cube root; cbrt(±0) = ±0, cbrt(±Infinity) = ±Infinity. */
export function cbrt(x: number): number {
  if (x !== x) return NaN;
  if (x === 0.0 || x === Infinity || x === -Infinity) return x;
  const ax = Math.abs(x);
  const e = ilogb(ax);
  const m = scalbn(ax, -e);
  const q = floor(e / 3);
  const r = e - 3 * q;
  const t0 = horner(m, CBRT_POLY);
  let u: number;
  let t: number;
  if (r === 0) {
    u = m;
    t = t0;
  } else if (r === 1) {
    u = 2.0 * m;
    t = t0 * CBRT2;
  } else {
    u = 4.0 * m;
    t = t0 * CBRT4;
  }
  t = (2.0 * t + u / (t * t)) / 3.0;
  t = (2.0 * t + u / (t * t)) / 3.0;
  twoProd(t, t);
  const t2 = rH;
  const t2e = rL;
  twoProd(t2, t);
  const t3 = rH;
  const t3e = rL;
  const res = (t3 - u) + (t3e + t2e * t);
  t -= res / (3.0 * t2);
  const v = scalbn(t, q);
  return x < 0.0 ? -v : v;
}

