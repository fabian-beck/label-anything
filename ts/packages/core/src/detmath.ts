let kSin = 0;
let kCos = 0;

/** (sin t°, cos t°) for |t| ≤ 45 into kSin, kCos. */
function scKernel(t: number): void {
  const at = Math.abs(t);
  if (at === 45.0) {
    kSin = t < 0.0 ? -SQRT_HALF : SQRT_HALF;
    kCos = SQRT_HALF;
    return;
  }
  if (at === 30.0) {
    kSin = t < 0.0 ? -0.5 : 0.5;
    kCos = SQRT_3_4;
    return;
  }
  twoProd(t, D2R_HI);
  const p = rH;
  const pe = rL;
  fastTwoSum(p, pe + t * D2R_LO);
  const x = rH;
  const xx = rL;
  twoProd(x, x);
  const z = rH;
  const ze = rL;
  // sin(x + xx) = x − x³/6 + x⁵·SIN_POLY(x²) + xx·(1 − x²/2)
  twoProd(z, x);
  const v = rH;
  const ve = rL + ze * x;
  const q = v / 6.0;
  twoProd(q, 6.0);
  const p6 = rH;
  const p6e = rL;
  const ql = (((v - p6) - p6e) + ve) / 6.0;
  const rs = horner(z, SIN_POLY);
  fastTwoSum(x, -q);
  const s1 = rH;
  const s1e = rL;
  kSin = s1 + (s1e + ((v * z * rs - ql) + xx * (1.0 - 0.5 * z)));
  // cos(x + xx) = 1 − (z + ze)/2 + z²·COS_POLY(z) + z·ze/12 − sin(x)·xx
  const hz = 0.5 * z;
  const w = 1.0 - hz;
  const rc = horner(z, COS_POLY);
  kCos = w + ((((1.0 - w) - hz) - 0.5 * ze) + ((z * z) * rc + (z * ze * COS_C1X2 - s1 * xx)));
}

let oSin = 0;
let oCos = 0;

function sinCosInto(deg: number): void {
  if (deg !== deg || deg === Infinity || deg === -Infinity) {
    oSin = NaN;
    oCos = NaN;
    return;
  }
  const r = deg % 360.0;
  const a = Math.abs(r);
  let s: number;
  let c: number;
  if (a <= 45.0) {
    scKernel(a);
    s = kSin;
    c = kCos;
  } else if (a < 135.0) {
    scKernel(a - 90.0);
    s = kCos;
    c = -kSin;
  } else if (a <= 225.0) {
    scKernel(a - 180.0);
    s = -kSin;
    c = -kCos;
  } else if (a < 315.0) {
    scKernel(a - 270.0);
    s = -kCos;
    c = kSin;
  } else {
    scKernel(a - 360.0);
    s = kSin;
    c = kCos;
  }
  if (s === 0.0) s = 0.0;
  if (c === 0.0) c = 0.0;
  oSin = signBit(r) ? -s : s;
  oCos = c;
}

/**
 * [sin deg°, cos deg°]: exact reduction in degrees, then double-double radians.
 * Exact at multiples of 30° and 45° (sin/cos 45° = sqrt(0.5)); cos is never -0;
 * sin(k·180°) is +0 for k > 0 and -0 for k < 0; non-finite input → [NaN, NaN].
 */
export function sinCosDeg(deg: number): [number, number] {
  sinCosInto(deg);
  return [oSin, oCos];
}

/** sin(deg°), identical to sinCosDeg(deg)[0]. */
export function sinDeg(deg: number): number {
  sinCosInto(deg);
  return oSin;
}

/** cos(deg°), identical to sinCosDeg(deg)[1]. */
export function cosDeg(deg: number): number {
  sinCosInto(deg);
  return oCos;
}

/** atan(n/d) in degrees as a double-double in rH, rL, for finite 0 < n < d. */
function atanRatioDeg(n: number, d: number): void {
  const ed = ilogb(d);
  const en = ilogb(n);
  if (ed - en > 900) {
    const n1 = scalbn(n, -en);
    const d1 = scalbn(d, -ed);
    const q = n1 / d1;
    twoProd(q, d1);
    const ql = ((n1 - rH) - rL) / d1;
    twoProd(q, R2D_HI);
    const v = rH + (rL + (q * R2D_LO + ql * R2D_HI));
    rH = scalbn(v, en - ed);
    rL = 0.0;
    return;
  }
  const n1 = scalbn(n, -ed);
  const d1 = scalbn(d, -ed);
  const q = n1 / d1;
  twoProd(q, d1);
  const ql = ((n1 - rH) - rL) / d1;
  const j = (q * 8.0 + 0.5) | 0;
  const c = j * 0.125;
  twoProd(q, c);
  const cp = rH;
  const cpe = rL;
  twoSum(1.0, cp);
  const dh = rH;
  const dl = rL + (cpe + ql * c);
  const num = q - c;
  const wh = num / dh;
  twoProd(wh, dh);
  const p3 = rH;
  const p3e = rL;
  const wl = ((((num - p3) - p3e) + ql) - wh * dl) / dh;
  const zz = wh * wh;
  const poly = wh * zz * horner(zz, ATAN_POLY);
  const t = wl + poly;
  twoProd(wh, R2D_HI);
  const rp = rH;
  const rpe = rL;
  const rlo = rpe + (wh * R2D_LO + t * R2D_HI);
  twoSum(ATAN_TAB_HI[j] as number, rp);
  const s = rH;
  const se = rL;
  fastTwoSum(s, se + ((ATAN_TAB_LO[j] as number) + rlo));
}

/**
 * Angle of (x, y) in degrees in [-180, 180] with the special cases of C99 atan2:
 * atan2Deg(±0, +0) = ±0, atan2Deg(±0, -0) = ±180, atan2Deg(±Infinity, -Infinity) = ±135, …
 * Exact for |y| = |x| and on the axes.
 */
export function atan2Deg(y: number, x: number): number {
  if (x !== x || y !== y) return NaN;
  const nx = signBit(x);
  const ay = Math.abs(y);
  const ax = Math.abs(x);
  let mag: number;
  if (ay === 0.0) {
    mag = nx ? 180.0 : 0.0;
  } else if (ax === 0.0 || (ay === Infinity && ax < Infinity)) {
    mag = 90.0;
  } else if (ax === Infinity) {
    mag = ay === Infinity ? (nx ? 135.0 : 45.0) : nx ? 180.0 : 0.0;
  } else {
    let h: number;
    let l: number;
    if (ay === ax) {
      h = 45.0;
      l = 0.0;
    } else if (ay < ax) {
      atanRatioDeg(ay, ax);
      h = rH;
      l = rL;
    } else {
      atanRatioDeg(ax, ay);
      ddRsub(90.0, rH, rL);
      h = rH;
      l = rL;
    }
    if (nx) {
      ddRsub(180.0, h, l);
      h = rH;
      l = rL;
    }
    mag = h + l;
  }
  return signBit(y) ? -mag : mag;
}
