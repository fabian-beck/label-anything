// ---------------------------------------------------------------------------------------
// Double-double helpers. Results are returned in the registers `rH`, `rL` (no
// allocation); callers copy them into locals immediately.
// ---------------------------------------------------------------------------------------

let rH = 0;
let rL = 0;

/** Dekker's exact product: a·b = rH + rL. */
function twoProd(a: number, b: number): void {
  const p = a * b;
  let c = SPLITTER * a;
  const ah = c - (c - a);
  const al = a - ah;
  c = SPLITTER * b;
  const bh = c - (c - b);
  const bl = b - bh;
  rH = p;
  rL = (((ah * bh - p) + ah * bl) + al * bh) + al * bl;
}

/** Knuth's exact sum: a + b = rH + rL. */
function twoSum(a: number, b: number): void {
  const s = a + b;
  const bb = s - a;
  rH = s;
  rL = (a - (s - bb)) + (b - bb);
}

/** Dekker's exact sum for |a| ≥ |b|: a + b = rH + rL. */
function fastTwoSum(a: number, b: number): void {
  const s = a + b;
  rH = s;
  rL = b - (s - a);
}

function ddMul(ah: number, al: number, bh: number, bl: number): void {
  twoProd(ah, bh);
  const p = rH;
  const e = rL + (ah * bl + al * bh);
  fastTwoSum(p, e);
}

function ddRecip(h: number, l: number): void {
  const q = 1.0 / h;
  twoProd(q, h);
  const r = ((1.0 - rH) - rL) - q * l;
  fastTwoSum(q, r / h);
}

/** c − (h + l). */
function ddRsub(c: number, h: number, l: number): void {
  twoSum(c, -h);
  const s = rH;
  const e = rL;
  fastTwoSum(s, e - l);
}

/** c[0] + x·(c[1] + x·(… + x·c[n−1])), innermost first. */
function horner(x: number, c: readonly number[]): number {
  const n = c.length;
  let acc = c[n - 1] as number;
  for (let i = n - 2; i >= 0; i--) {
    acc = (c[i] as number) + x * acc;
  }
  return acc;
}

/** Unbiased binary exponent of a finite, non-zero x (subnormals included). */
function ilogb(x: number): number {
  const e = (hiWord(x) >>> 20) & 0x7ff;
  if (e === 0) return ((hiWord(x * TWO54) >>> 20) & 0x7ff) - 1077;
  return e - 1023;
}

/** x · 2^n with a single rounding (only when the result is subnormal). */
function scalbn(x: number, n: number): number {
  let y = x;
  if (n > 1023) {
    y *= TWO1023;
    n -= 1023;
    if (n > 1023) {
      y *= TWO1023;
      n -= 1023;
      if (n > 1023) n = 1023;
    }
  } else if (n < -1022) {
    y *= TWO_M969;
    n += 969;
    if (n < -1022) {
      y *= TWO_M969;
      n += 969;
      if (n < -1022) n = -1022;
    }
  }
  return y * fromWords((0x3ff + n) << 20, 0);
}

