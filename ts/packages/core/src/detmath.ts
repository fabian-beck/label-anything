// ---------------------------------------------------------------------------------------
// Bit access (endianness-safe: the word order of the Float64Array view is detected)
// ---------------------------------------------------------------------------------------

const F64 = new Float64Array(1);
const U32 = new Uint32Array(F64.buffer);
const LITTLE_ENDIAN = new Uint8Array(new Uint16Array([1]).buffer)[0] === 1;
const HI = LITTLE_ENDIAN ? 1 : 0;
const LO = LITTLE_ENDIAN ? 0 : 1;

function hiWord(x: number): number {
  F64[0] = x;
  return U32[HI] as number;
}

function loWord(x: number): number {
  F64[0] = x;
  return U32[LO] as number;
}

function fromWords(hi: number, lo: number): number {
  U32[HI] = hi;
  U32[LO] = lo;
  return F64[0] as number;
}

/** Sign bit of `x` (true for -0 and negative numbers). */
function signBit(x: number): boolean {
  return hiWord(x) >>> 31 === 1;
}

/** The IEEE-754 bit pattern of `x` as `"0x"` + 16 hex digits (NaN → canonical NaN). */
export function f64ToHex(x: number): string {
  if (x !== x) return "0x7ff8000000000000";
  const h = hiWord(x).toString(16).padStart(8, "0");
  const l = loWord(x).toString(16).padStart(8, "0");
  return `0x${h}${l}`;
}

/** The double with the bit pattern `"0x"` + 16 hex digits. */
export function hexToF64(hex: string): number {
  const s = hex.startsWith("0x") || hex.startsWith("0X") ? hex.slice(2) : hex;
  const t = s.padStart(16, "0");
  return fromWords(parseInt(t.slice(0, 8), 16) >>> 0, parseInt(t.slice(8, 16), 16) >>> 0);
}

